const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: store.get("lang", "zh"),          // 主语言：中文
  fallbackLocale: "en",
  messages: { zh, en },
});

export default i18n;

export function setLang(code) {
  i18n.global.locale.value = code === "en" ? "en" : "zh";
  store.set("lang", i18n.global.locale.value);
  document.documentElement.lang = i18n.global.locale.value === "zh" ? "zh-CN" : "en";
}
